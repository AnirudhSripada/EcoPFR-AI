CONVERSION_TARGET = 0.90


def optimization_objective(params):

    # Extract optimization variables
    T, P, tau, CA0 = params

    # Create input DataFrame
    input_df = pd.DataFrame(
        [[T, P, tau, CA0]],
        columns=features
    )

    # XGBoost predictions
    predicted_conversion = float(
        xgb_conversion.predict(
            input_df
        )[0]
    )

    predicted_energy = float(
        xgb_energy.predict(
            input_df
        )[0]
    )

    # --------------------------------------------------------
    # Conversion constraint
    #
    # X >= 0.90
    # --------------------------------------------------------

    if predicted_conversion < CONVERSION_TARGET:

        deficit = (
            CONVERSION_TARGET
            - predicted_conversion
        )

        penalty = 10000 * deficit**2

        return (
            predicted_energy
            + penalty
        )

    # If conversion requirement is satisfied
    return predicted_energy


