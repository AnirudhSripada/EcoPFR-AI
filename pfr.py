# ============================================================
# 4. ARRHENIUS EQUATION
# ============================================================

def reaction_rate_constant(T):
    """
    Calculate first-order reaction rate constant.

    k = K0 * exp(-EA / RT)

    Parameters
    ----------
    T : float
        Temperature in Kelvin

    Returns
    -------
    k : float
        Reaction rate constant in 1/min
    """

    k = K0 * np.exp(-EA / (R * T))

    return k


# ============================================================
# 5. PFR CONVERSION MODEL
# ============================================================

def pfr_conversion(T, tau, CA0):
    """
    Calculate conversion for an isothermal
    first-order PFR.

    For first-order reaction:

        A -> B

        -rA = k CA

    PFR solution:

        X = 1 - exp(-k*tau)

    CA0 is retained as an input because it is one
    of the requested ML features.

    For this simplified first-order,
    constant-density model, conversion is
    mathematically independent of CA0.
    """

    k = reaction_rate_constant(T)

    X = 1.0 - np.exp(-k * tau)

    # Keep conversion physically meaningful
    X = np.clip(X, 0.0, 0.999999)

    return X


