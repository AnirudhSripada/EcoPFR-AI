# 6. ENERGY MODEL
# ============================================================

def calculate_energy(T, P, tau, CA0):
    """
    Calculate approximate PFR energy consumption.

    Energy components:

        1. Heating energy
        2. Reaction energy
        3. Pumping energy

    Returns
    -------
    heating_energy_kWh
    reaction_energy_kWh
    pumping_energy_kWh
    total_energy_kWh
    """

    # --------------------------------------------------------
    # Flow rate from residence time
    #
    # tau = V / Q
    #
    # Q = V / tau
    # --------------------------------------------------------

    Q = REACTOR_VOLUME / tau      # L/min

    # --------------------------------------------------------
    # Conversion
    # --------------------------------------------------------

    X = pfr_conversion(T, tau, CA0)

    # ========================================================
    # 1. HEATING ENERGY
    # ========================================================

    T_FEED = 298.15              # K

    # Mass flow
    mass_flow_kg_min = Q * DENSITY

    # Convert CP from J/g/K to J/kg/K
    CP_KG = CP * 1000

    # Sensible heating
    heating_power_J_min = (
        mass_flow_kg_min
        * CP_KG
        * max(T - T_FEED, 0)
    )

    # Convert J/min to kWh
    heating_energy_kWh = (
        heating_power_J_min
        * 60
        / 3.6e6
    )

    # Correct for heater efficiency
    heating_energy_kWh /= HEATER_EFFICIENCY

    # ========================================================
    # 2. REACTION ENERGY
    # ========================================================

    # Moles reacted per minute
    mol_reacted_min = (
        Q
        * CA0
        * X
    )

    reaction_power_J_min = (
        mol_reacted_min
        * abs(DELTA_H)
    )

    reaction_energy_kWh = (
        reaction_power_J_min
        * 60
        / 3.6e6
    )

    # ========================================================
    # 3. PUMPING ENERGY
    # ========================================================

    # Simplified pressure requirement
    delta_P = P * 1e5       # bar -> Pa

    # L/min -> m3/s
    Q_m3_s = Q * 1e-3 / 60

    pump_power_W = (
        delta_P
        * Q_m3_s
        / PUMP_EFFICIENCY
    )

    pumping_energy_kWh = pump_power_W / 1000

    # ========================================================
    # TOTAL ENERGY
    # ========================================================

    total_energy_kWh = (
        heating_energy_kWh
        + reaction_energy_kWh
        + pumping_energy_kWh
    )

    return (
        heating_energy_kWh,
        reaction_energy_kWh,
        pumping_energy_kWh,
        total_energy_kWh
    )


