# 32. SIMPLE USER PREDICTION FUNCTION
# ============================================================

def predict_pfr(
    temperature,
    pressure,
    residence_time,
    feed_concentration
):
    """
    Give operating conditions and receive
    predicted PFR performance.
    """

    user_input = pd.DataFrame(
        [[
            temperature,
            pressure,
            residence_time,
            feed_concentration
        ]],
        columns=features
    )

    conversion = float(
        xgb_conversion.predict(
            user_input
        )[0]
    )

    energy = float(
        xgb_energy.predict(
            user_input
        )[0]
    )

    solar = min(
        SOLAR_ENERGY,
        energy
    )

    grid = max(
        energy - SOLAR_ENERGY,
        0
    )

    co2 = (
        grid
        * GRID_EMISSION_FACTOR
    )

    print("\n================================")
    print("PFR PREDICTION")
    print("================================")

    print(
        f"Temperature        : "
        f"{temperature:.2f} K"
    )

    print(
        f"Pressure           : "
        f"{pressure:.2f} bar"
    )

    print(
        f"Residence time     : "
        f"{residence_time:.2f} min"
    )

    print(
        f"Feed concentration : "
        f"{feed_concentration:.2f} mol/L"
    )

    print("--------------------------------")

    print(
        f"Predicted conversion: "
        f"{conversion*100:.2f}%"
    )

    print(
        f"Predicted energy    : "
        f"{energy:.6f} kWh"
    )

    print(
        f"Solar energy used   : "
        f"{solar:.6f} kWh"
    )

    print(
        f"Grid energy         : "
        f"{grid:.6f} kWh"
    )

    print(
        f"CO2 emissions       : "
        f"{co2:.6f} kg CO2e"
    )

    if conversion >= 0.90:

        print(
            "\n✓ Conversion requirement satisfied."
        )

    else:

        print(
            "\n✗ Conversion below 90%."
        )

    return {
        "conversion": conversion,
        "energy_kWh": energy,
        "solar_kWh": solar,
        "grid_kWh": grid,
        "CO2_kg": co2
    }


